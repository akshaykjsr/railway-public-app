function trim(rows) {
  let top = 0; let bottom = rows.length - 1;
  while (top < rows.length && !rows[top].includes('1')) top++;
  while (bottom >= 0 && !rows[bottom].includes('1')) bottom--;
  return rows.slice(top, bottom + 1);
}
